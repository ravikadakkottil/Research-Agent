"""
FastAPI app: the same pipeline + agent, served over HTTP.

Endpoints
  GET  /                     web page (static/index.html)
  GET  /health               "is the server up?" (used by monitors / Docker later)
  POST /api/search           run the pipeline, return the full result as JSON
  POST /api/agent            run the tool-calling agent, return its answer
  GET  /api/search/stream    same as /api/search but streams live progress (SSE)
  GET  /api/agent/stream     same as /api/agent  but streams live progress (SSE)
  GET  /docs                 interactive API docs (generated by FastAPI)

Why streaming? A research run takes ~5-10 s (deep research: minutes). Instead of
a silent spinner, the page receives each step as it happens — the same `on_step`
callback the CLI prints, just sent over the network.

SSE (Server-Sent Events) = one long HTTP response where the server writes
small text messages:
    event: step
    data: "1) Asking LLM for a search plan..."

Browsers read it with the built-in EventSource API. No extra libraries.
"""

from __future__ import annotations

import asyncio
import json
import logging
from collections.abc import AsyncIterator, Awaitable, Callable
from contextlib import asynccontextmanager
from pathlib import Path
from typing import Any

from fastapi import FastAPI, HTTPException, Query, Request
from fastapi.responses import FileResponse, StreamingResponse

from research_agent import __version__
from research_agent.agent.loop import run_tool_agent
from research_agent.api.schemas import AgentAnswer, ErrorBody, QuestionRequest
from research_agent.config import Settings, get_settings
from research_agent.llm import LLMOutputError
from research_agent.models import SearchResult
from research_agent.pipeline import StepCallback, run_paper_search
from research_agent.sources.openalex import (
    OpenAlexClient,
    OpenAlexRateLimitError,
    create_openalex_client,
)

logger = logging.getLogger(__name__)
STATIC_DIR = Path(__file__).parent / "static"


# ---------------------------------------------------------------------------
# Lifespan: things created once at startup and closed at shutdown
# ---------------------------------------------------------------------------
@asynccontextmanager
async def lifespan(app: FastAPI) -> AsyncIterator[None]:
    """
    One shared OpenAlex client for all requests: one connection pool, one cache,
    one concurrency limit — instead of opening new connections per request.
    """
    settings = get_settings()
    async with create_openalex_client(settings) as client:
        app.state.settings = settings
        app.state.openalex = client
        yield


app = FastAPI(
    title="Research Agent API",
    version=__version__,
    description="Find relevant, influential and recent papers on a topic and summarize them.",
    lifespan=lifespan,
)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def _request_settings(request: Request, use_cache: bool) -> tuple[Settings, OpenAlexClient | None]:
    """
    Settings + client for one request.

    use_cache=False -> settings copy with caching off, and no shared client
    (the pipeline then creates a temporary uncached one).
    """
    settings: Settings = request.app.state.settings
    if use_cache:
        return settings, request.app.state.openalex
    return settings.model_copy(update={"cache_enabled": False}), None


def _to_http_error(exc: Exception) -> HTTPException:
    """Translate our domain errors into HTTP status codes."""
    if isinstance(exc, OpenAlexRateLimitError):
        return HTTPException(status_code=429, detail=str(exc))
    if isinstance(exc, LLMOutputError):
        return HTTPException(status_code=502, detail="The LLM returned an unexpected format.")
    logger.exception("Unhandled error", exc_info=exc)
    return HTTPException(status_code=500, detail=f"{type(exc).__name__}: {exc}")


def _sse(event: str, data: Any) -> str:
    """Format one Server-Sent Event."""
    return f"event: {event}\ndata: {json.dumps(data, ensure_ascii=False)}\n\n"


async def _stream_run(run: Callable[[StepCallback], Awaitable[Any]]) -> AsyncIterator[str]:
    """
    Run a job in the background and stream its progress as SSE.

        job --on_step--> asyncio.Queue --> this generator --> HTTP response

    The queue decouples the job (producer) from the HTTP response (consumer).
    If the browser disconnects, the `finally` cancels the job so it stops
    using LLM / OpenAlex budget for nobody.
    """
    queue: asyncio.Queue[tuple[str, Any]] = asyncio.Queue()

    async def worker() -> None:
        try:
            result = await run(lambda msg: queue.put_nowait(("step", msg)))
            await queue.put(("result", result))
        except Exception as exc:  # noqa: BLE001 - every failure becomes an error event
            http_error = _to_http_error(exc)
            await queue.put(
                ("failure", {"status": http_error.status_code, "detail": http_error.detail})
            )
        finally:
            await queue.put(("done", None))

    task = asyncio.create_task(worker())
    try:
        while True:
            event, data = await queue.get()
            if event == "done":
                break
            yield _sse(event, data)
    finally:
        task.cancel()


def _sse_response(generator: AsyncIterator[str]) -> StreamingResponse:
    return StreamingResponse(
        generator,
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},  # don't buffer
    )


_ERRORS: dict[int | str, dict[str, Any]] = {
    429: {"model": ErrorBody, "description": "OpenAlex daily budget used up"},
    502: {"model": ErrorBody, "description": "LLM returned an unexpected format"},
}


# ---------------------------------------------------------------------------
# Routes
# ---------------------------------------------------------------------------
@app.get("/", include_in_schema=False)
async def index() -> FileResponse:
    return FileResponse(STATIC_DIR / "index.html")


@app.get("/health", tags=["meta"])
async def health() -> dict[str, str]:
    return {"status": "ok", "version": __version__}


@app.post("/api/search", response_model=SearchResult, responses=_ERRORS, tags=["research"])
async def search(body: QuestionRequest, request: Request) -> SearchResult:
    """Run the fixed pipeline (plan -> buckets -> select -> synthesize)."""
    settings, client = _request_settings(request, body.use_cache)
    try:
        return await run_paper_search(body.question, settings=settings, client=client)
    except Exception as exc:
        raise _to_http_error(exc) from exc


@app.post("/api/agent", response_model=AgentAnswer, responses=_ERRORS, tags=["research"])
async def agent(body: QuestionRequest, request: Request) -> AgentAnswer:
    """Run the tool-calling agent (the LLM decides which OpenAlex tools to use)."""
    settings, _ = _request_settings(request, body.use_cache)
    try:
        answer = await run_tool_agent(body.question, settings=settings)
    except Exception as exc:
        raise _to_http_error(exc) from exc
    return AgentAnswer(question=body.question, answer=answer)


@app.get("/api/search/stream", tags=["streaming"])
async def search_stream(
    request: Request,
    question: str = Query(min_length=3, max_length=500),
    use_cache: bool = True,
) -> StreamingResponse:
    """Pipeline with live progress. Events: `step` (text), `result` (JSON), `failure`."""
    settings, client = _request_settings(request, use_cache)

    async def run(on_step: StepCallback) -> dict[str, Any]:
        result = await run_paper_search(question, on_step=on_step, settings=settings, client=client)
        return result.model_dump(mode="json")

    return _sse_response(_stream_run(run))


@app.get("/api/agent/stream", tags=["streaming"])
async def agent_stream(
    request: Request,
    question: str = Query(min_length=3, max_length=500),
    use_cache: bool = True,
) -> StreamingResponse:
    """Agent with live progress. Events: `step` (text), `result` (JSON), `failure`."""
    settings, _ = _request_settings(request, use_cache)

    async def run(on_step: StepCallback) -> dict[str, Any]:
        answer = await run_tool_agent(question, on_step=on_step, settings=settings)
        return {"question": question, "answer": answer}

    return _sse_response(_stream_run(run))
