"""
The golden dataset (answer key) and how a retrieved paper is matched to it.

Matching is deliberately generous — any ONE identifier is enough:
  OpenAlex ID  |  any known DOI  |  normalized title
because OpenAlex can hold the same paper as several records (preprint vs
published version). A strict match would count found papers as missed.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Literal

from pydantic import BaseModel

from research_agent.models import Paper
from research_agent.retrieval.selection import normalize_title
from research_agent.sources.openalex import short_id


def bare_doi(value: str | None) -> str:
    """'https://doi.org/10.1/ABC' -> '10.1/abc'"""
    return (value or "").strip().lower().removeprefix("https://doi.org/")


class GoldenPaper(BaseModel):
    title: str
    kind: Literal["foundational", "recent"]
    openalex_ids: list[str] = []
    dois: list[str] = []
    titles: list[str] = []
    year: int | None = None
    cited_by_count: int | None = None

    def matches(self, paper: Paper) -> bool:
        if paper.openalex_id and short_id(paper.openalex_id) in self.openalex_ids:
            return True
        if paper.doi and bare_doi(paper.doi) in {bare_doi(d) for d in self.dois}:
            return True
        title_key = normalize_title(paper.title)
        return bool(title_key) and title_key in {normalize_title(t) for t in self.titles}


class GoldenTopic(BaseModel):
    id: str
    field: str = ""
    question: str
    must_include: list[GoldenPaper]


def load_golden(path: Path) -> list[GoldenTopic]:
    """Load golden.lock.json (generated by evals/verify_golden.py)."""
    data = json.loads(path.read_text(encoding="utf-8"))
    return [GoldenTopic.model_validate(t) for t in data["topics"]]
